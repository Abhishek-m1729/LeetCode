/**
 * Definition for singly-linked list.
 * struct ListNode {
 *     int val;
 *     ListNode *next;
 *     ListNode(int x) : val(x), next(NULL) {}
 * };
 */
 struct ListNode *first = NULL;
class Solution {
public:
    void deleteNode(ListNode* node) {
       ListNode *p = node->next;
       swap(p->val, node->val);
       node->next = p->next;
       delete p;
    }
};

